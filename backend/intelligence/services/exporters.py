"""Exporters.

Seven formats, no new runtime dependency:

  csv      — the workhorse; source URL + timestamp on every row
  xlsx     — a real Office Open XML workbook, written with stdlib zipfile
  json     — full fidelity, the API's own shape
  markdown — paste-ready for a client deck or a Slack thread
  html     — a self-contained, printable, white-label-ready document
  xml      — for a CRM or an aggregator
  pdf      — via the reportlab dependency the compliance export already
             uses, with the same hand-rolled fallback when it is absent

**Every exporter is evidence-first.** `source_url` and `detected_at` are on
every row, so a downloaded file is self-auditing: a reader can always trace
a claim back to the page it came from. Nothing is summarised in a way that
loses the before/after pair.
"""

import csv
import io
import json
import zipfile
from datetime import datetime, timezone as dt_timezone
from html import escape
from xml.sax.saxutils import escape as xml_escape

from .product_diff import SEVERITY_LABELS

# Column order is the exporter's contract for csv/xlsx/xml.
COLUMNS = [
    ("detected_at", "Detected at"),
    ("competitor", "Competitor"),
    ("kind", "Category"),
    ("severity", "Severity"),
    ("headline", "What changed"),
    ("before", "Before"),
    ("after", "After"),
    ("rule", "Classification rule"),
    ("basis", "Why"),
    ("source_url", "Source URL"),
    ("monitor_name", "Monitor"),
    ("monitor_url", "Monitor URL"),
    ("signal_event_id", "Event id"),
    ("evidence", "Evidence"),
]

GENERATED_NOTE = (
    "Generated by Sitemyra from publicly accessible web pages. Every row "
    "carries its source URL and detection time so the claim can be checked. "
    "Sitemyra reports what a page published; it does not know a competitor's "
    "revenue, customers or intent."
)


def flatten_event(event) -> dict:
    competitor = getattr(event, "competitor", None)
    monitor = getattr(event, "monitor", None)
    evidence = event.evidence or {}
    return {
        "detected_at": event.detected_at.isoformat() if event.detected_at else "",
        "competitor": competitor.name if competitor else "",
        "kind": event.kind,
        "severity": SEVERITY_LABELS.get(event.severity, event.severity),
        "headline": event.headline,
        "before": event.before,
        "after": event.after,
        "rule": evidence.get("rule", ""),
        "basis": evidence.get("basis", "") or event.summary,
        "source_url": event.source_url,
        "monitor_name": monitor.name if monitor else "",
        "monitor_url": monitor.url if monitor else "",
        "signal_event_id": str(event.id),
        "evidence": json.dumps(evidence, sort_keys=True)[:500] if evidence else "",
    }


def flatten_competitor(competitor) -> dict:
    return {
        "detected_at": competitor.last_activity_at.isoformat()
        if competitor.last_activity_at
        else "",
        "competitor": competitor.name,
        "kind": "competitor",
        "severity": "",
        "headline": f"{competitor.relationship}: {competitor.homepage_url}",
        "before": "",
        "after": "",
        "rule": "",
        "basis": "; ".join(competitor.relationship_reasons or []),
        "source_url": competitor.homepage_url,
        "monitor_name": "",
        "monitor_url": "",
        "signal_event_id": "",
        "evidence": json.dumps({"signals": competitor.signals or []}, sort_keys=True)[:500],
    }


def rows_from(events=(), competitors=()):
    rows = [flatten_competitor(item) for item in competitors]
    rows.extend(flatten_event(item) for item in events)
    rows.sort(key=lambda row: row["detected_at"], reverse=True)
    return rows


