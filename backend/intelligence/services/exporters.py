def to_markdown(rows, title="Competitive intelligence export", meta=None) -> bytes:
    lines = [f"# {title}", ""]
    generated = datetime.now(dt_timezone.utc)
    lines.append(f"Generated {generated.strftime('%Y-%m-%d %H:%M UTC')}")
    if meta:
        for key in sorted(meta):
            if meta[key] not in (None, "", [], {}):
                lines.append(f"- {key.replace('_', ' ').title()}: {meta[key]}")
    lines.extend(["", f"_{GENERATED_NOTE}_", ""])
    if not rows:
        lines.append("_No changes were recorded for this selection._")
        return "\n".join(lines).encode("utf-8")

    lines.append(f"**{len(rows)} change(s)**")
    lines.append("")
    for row in rows:
        when = (row.get("detected_at") or "")[:16].replace("T", " ")
        lines.append(f"### {row.get('competitor') or 'Unknown'} — {row.get('headline') or ''}")
        lines.append("")
        lines.append(f"- **Detected:** {when} UTC")
        lines.append(f"- **Category:** {row.get('kind') or '—'} · **Severity:** {row.get('severity') or '—'}")
        if row.get("before") or row.get("after"):
            lines.append(f"- **Before:** {row.get('before') or '—'}")
            lines.append(f"- **After:** {row.get('after') or '—'}")
        if row.get("basis"):
            lines.append(f"- **Why:** {row['basis']}")
        if row.get("rule"):
            lines.append(f"- **Rule:** `{row['rule']}`")
        if row.get("source_url"):
            lines.append(f"- **Source:** {row['source_url']}")
        lines.append("")
    return "\n".join(lines).encode("utf-8")


