def to_html(rows, title="Competitive intelligence report", meta=None, branding=None) -> bytes:
    brand = dict(_BRAND_DEFAULT)
    brand.update(branding or {})
    accent = escape(str(brand.get("primary_color") or "#0052ff"))
    parts = [
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">",
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{escape(title)}</title><style>",
        "body{font:15px/1.6 -apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;",
        "color:#0f172a;background:#fff;margin:0;padding:40px 24px}",
        ".wrap{max-width:900px;margin:0 auto}",
        f"h1{{font-size:28px;margin:0 0 4px}}h2{{font-size:18px;margin:0 0 4px}}",
        ".muted{color:#64748b;font-size:13px}",
        f"table{{width:100%;border-collapse:collapse;margin-top:24px;font-size:13px}}",
        "th,td{text-align:left;padding:9px 10px;border-bottom:1px solid #e2e8f0;vertical-align:top}",
        "th{background:#f8fafc;font-weight:600;white-space:nowrap}",
        f"a{{color:{accent}}}code{{background:#f1f5f9;padding:1px 5px;border-radius:4px;font-size:12px}}",
        ".pill{display:inline-block;padding:2px 8px;border-radius:999px;background:#f1f5f9;font-size:11px}",
        ".note{margin-top:28px;padding:14px 16px;background:#f8fafc;border-radius:12px;font-size:12px;color:#475569}",
        "@media print{body{padding:0}}",
        "</style></head><body><div class=\"wrap\">",
        f'<p class="pill" style="background:{accent}1a;color:{accent}">{escape(str(brand.get("tagline") or ""))}</p>',
        f"<h1>{escape(title)}</h1>",
        f'<p class="muted">{escape(str(brand.get("agency_name") or "Sitemyra"))} · generated '
        f'{datetime.now(dt_timezone.utc).strftime("%Y-%m-%d %H:%M UTC")}</p>',
    ]
    if meta:
        parts.append("<p class=\"muted\">")
        for key in sorted(meta):
            if meta[key] not in (None, "", [], {}):
                parts.append(
                    f"<br>{escape(str(key.replace('_', ' ').title()))}: "
                    f"{escape(str(meta[key]))}"
                )
        parts.append("</p>")

    if not rows:
        parts.append("<p class=\"muted\">No changes were recorded for this selection.</p>")
    else:
        parts.append(f"<p class=\"muted\">{len(rows)} change(s)</p><table><thead><tr>")
        parts.append(
            "<th>Detected</th><th>Competitor</th><th>Category</th>"
            "<th>What changed</th><th>Before</th><th>After</th><th>Source</th></tr></thead><tbody>"
        )
        for row in rows:
            when = escape((row.get("detected_at") or "")[:19].replace("T", " "))
            source = row.get("source_url") or ""
            source_cell = (
                f'<a href="{escape(source)}">{escape(source[:60])}</a>' if source else "—"
            )
            parts.append(
                "<tr>"
                f"<td>{when}</td>"
                f"<td>{escape(str(row.get('competitor') or '—'))}</td>"
                f"<td>{escape(str(row.get('kind') or '—'))}</td>"
                f"<td>{escape(str(row.get('headline') or '—'))}"
                + (
                    f"<br><span class=\"muted\">{escape(str(row.get('basis'))[:160])}</span>"
                    if row.get("basis")
                    else ""
                )
                + "</td>"
                f"<td>{escape(str(row.get('before') or '—'))}</td>"
                f"<td>{escape(str(row.get('after') or '—'))}</td>"
                f"<td>{source_cell}</td>"
                "</tr>"
            )
        parts.append("</tbody></table>")

    parts.append(f'<p class="note">{escape(GENERATED_NOTE)}</p>')
    if brand.get("show_sitemyra_credit"):
        parts.append(
            '<p class="muted" style="margin-top:18px">Generated with Sitemyra.</p>'
        )
    if brand.get("footer"):
        parts.append(f'<p class="muted">{escape(str(brand["footer"]))}</p>')
    parts.append("</div></body></html>")
    return "".join(parts).encode("utf-8")


