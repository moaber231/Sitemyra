FORMATS = {
    "csv": ("text/csv", "csv"),
    "xlsx": (
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "xlsx",
    ),
    "json": ("application/json", "json"),
    "markdown": ("text/markdown; charset=utf-8", "md"),
    "md": ("text/markdown; charset=utf-8", "md"),
    "html": ("text/html; charset=utf-8", "html"),
    "xml": ("application/xml", "xml"),
    "pdf": ("application/pdf", "pdf"),
}


def render(fmt: str, rows, title="Competitive intelligence export", meta=None, branding=None, sheet_name="Intelligence") -> bytes:
    key = (fmt or "csv").strip().lower()
    if key == "csv":
        return to_csv(rows)
    if key == "xlsx":
        return to_xlsx(rows, sheet_name=sheet_name)
    if key == "json":
        return to_json(rows, meta)
    if key in ("markdown", "md"):
        return to_markdown(rows, title=title, meta=meta)
    if key == "html":
        return to_html(rows, title=title, meta=meta, branding=branding)
    if key == "xml":
        return to_xml(rows, meta)
    if key == "pdf":
        return to_pdf(rows, title=title, meta=meta)
    raise ValueError(f"unsupported export format: {fmt}")
