def to_xml(rows, meta=None) -> bytes:
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<sitemyra-intelligence xmlns="https://sitemyra.com/schema/intelligence/1" version="1">',
        f"<generated-at>{datetime.now(dt_timezone.utc).isoformat()}</generated-at>",
        f"<note>{xml_escape(GENERATED_NOTE)}</note>",
    ]
    if meta:
        parts.append("<meta>")
        for key in sorted(meta):
            parts.append(
                f"<{key}>{xml_escape(str(meta[key]))}</{key}>"
            )
        parts.append("</meta>")
    parts.append(f'<change-count>{len(rows)}</change-count>')
    parts.append("<changes>")
    for row in rows:
        parts.append("<change>")
        for key, _label in COLUMNS:
            value = row.get(key, "")
            parts.append(f"<{key}>{xml_escape(str(value))}</{key}>")
        parts.append("</change>")
    parts.append("</changes></sitemyra-intelligence>")
    return "".join(parts).encode("utf-8")


