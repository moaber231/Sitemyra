def to_csv(rows) -> bytes:
    buffer = io.StringIO()
    writer = csv.DictWriter(
        buffer, fieldnames=[key for key, _label in COLUMNS], extrasaction="ignore"
    )
    writer.writeheader()
    for row in rows:
        writer.writerow({key: row.get(key, "") for key, _label in COLUMNS})
    buffer.write("\n")
    buffer.write(f"# {GENERATED_NOTE}\n")
    return buffer.getvalue().encode("utf-8")


