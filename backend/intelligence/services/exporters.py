def to_pdf(rows, title="Competitive intelligence report", meta=None) -> bytes:
    try:
        from reportlab.lib.pagesizes import landscape, letter
        from reportlab.pdfgen import canvas
    except ImportError:
        return _fallback_pdf(rows, title)

    try:
        buffer = io.BytesIO()
        page_size = landscape(letter) if len(COLUMNS) > 4 else letter
        pdf = canvas.Canvas(buffer, pagesize=page_size)
        width, height = page_size
        y = height - 46
        pdf.setFont("Helvetica-Bold", 15)
        pdf.drawString(36, y, title[:110])
        y -= 15
        pdf.setFont("Helvetica", 8)
        pdf.drawString(
            36, y, f"Generated {datetime.now(dt_timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} UTC  |  {len(rows)} change(s)"
        )
        y -= 12
        pdf.drawString(36, y, "Every row carries its source URL and detection time.")
        y -= 18

        def ensure(needed=12):
            nonlocal y
            if y < 50 + needed:
                pdf.showPage()
                y = height - 46

        pdf.setFont("Helvetica-Bold", 7)
        columns = [
            ("Detected", 76), ("Competitor", 78), ("Cat", 48), ("What changed", 168),
            ("Before", 76), ("After", 76), ("Source", 150),
        ]
        x = 36
        for label, span in columns:
            pdf.drawString(x, y, label)
            x += span
        y -= 6
        pdf.line(36, y, width - 36, y)
        y -= 10

        pdf.setFont("Helvetica", 7)
        for row in rows[:2000]:
            ensure(20)
            values = [
                (row.get("detected_at") or "")[:19].replace("T", " "),
                (row.get("competitor") or "")[:18],
                (row.get("kind") or "")[:10],
                (row.get("headline") or "")[:40],
                (row.get("before") or "")[:18],
                (row.get("after") or "")[:18],
                (row.get("source_url") or "")[:44],
            ]
            x = 36
            for (value, (_label, span)) in zip(values, columns):
                if value:
                    pdf.drawString(x, y, str(value))
                x += span
            y -= 9
            source = row.get("source_url") or ""
            if source:
                pdf.setFont("Helvetica", 6)
                ensure(8)
                pdf.drawString(44, y, f"rule={row.get('rule') or '-'}  {source[:120]}")
                pdf.setFont("Helvetica", 7)
                y -= 9
            y -= 2
        ensure(30)
        pdf.setFont("Helvetica-Oblique", 6)
        for line in _wrap(GENERATED_NOTE, 150):
            pdf.drawString(36, y, line)
            y -= 8
        pdf.save()
        return buffer.getvalue()
    except Exception:
        return _fallback_pdf(rows, title)


def _wrap(text, width):
    words = str(text).split()
    lines, current = [], ""
    for word in words:
        if len(current) + len(word) + 1 > width:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}".strip()
    if current:
        lines.append(current)
    return lines


def _fallback_pdf(rows, title):
    """A minimal but valid PDF, so the endpoint works without reportlab.

    Same approach as the existing compliance export: never fail a download
    because an optional library is missing.
    """
    lines = [title[:110], f"Generated {datetime.now(dt_timezone.utc).isoformat()}", ""]
    for row in rows[:400]:
        lines.append(
            f"{(row.get('detected_at') or '')[:19]}  {row.get('competitor') or ''}  "
            f"{row.get('kind') or ''}  {row.get('headline') or ''}"
        )
        if row.get("before") or row.get("after"):
            lines.append(f"    before: {row.get('before') or '-'}   after: {row.get('after') or '-'}")
        if row.get("source_url"):
            lines.append(f"    source: {row['source_url'][:100]}")
    lines.extend(["", GENERATED_NOTE])
    text = "\n".join(lines)
    escaped = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    content = f"BT /F1 9 Tf 36 750 Td ({escaped}) Tj ET"
    return (
        "%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n"
        "2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj\n"
        "3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 792 612]/Contents 4 0 R>>endobj\n"
        f"4 0 obj<</Length {len(content)}>>stream\n{content}\nendstream\nendobj\n"
        "trailer<</Root 1 0 R>>\n%%EOF"
    ).encode("latin-1", errors="replace")


