_XLSX_CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
</Types>"""

_XLSX_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>"""

_XLSX_WORKBOOK = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="Intelligence" sheetId="1" r:id="rId1"/></sheets>
</workbook>"""

_XLSX_WORKBOOK_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>"""

_XLSX_STYLES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<fonts count="2"><font><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="11"/><name val="Calibri"/></font></fonts>
<fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills>
<borders count="1"><border/></borders>
<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
<cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/><xf numFmtId="0" fontId="1" fillId="0" borderId="0" xfId="0" applyFont="1"/></cellXfs>
</styleSheet>"""

_MAX_XLSX_ROWS = 50000
_MAX_XLSX_CELL = 32000


def _column_name(index: int) -> str:
    name = ""
    index += 1
    while index:
        index, remainder = divmod(index - 1, 26)
        name = chr(65 + remainder) + name
    return name


def _xlsx_cell(reference: str, value, style: int = 0) -> str:
    style_attr = f' s="{style}"' if style else ""
    if value is None or value == "":
        return f'<c r="{reference}"{style_attr}/>'
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return f'<c r="{reference}"{style_attr}><v>{value}</v></c>'
    text = str(value)
    if len(text) > _MAX_XLSX_CELL:
        text = text[:_MAX_XLSX_CELL]
    return (
        f'<c r="{reference}" t="inlineStr"{style_attr}><is><t xml:space="preserve">'
        f"{escape(text)}</t></is></c>"
    )


def to_xlsx(rows, sheet_name="Intelligence") -> bytes:
    """A valid single-sheet .xlsx built with zipfile + XML only.

    Excel, Numbers, LibreOffice and Google Sheets all open this. Written by
    hand rather than pulling in openpyxl: a workbook writer is ~100 lines
    and a new dependency is a permanent supply-chain surface.
    """
    sheet_rows = []
    header_cells = "".join(
        _xlsx_cell(f"{_column_name(index)}1", label, style=1)
        for index, (_key, label) in enumerate(COLUMNS)
    )
    sheet_rows.append(f'<row r="1">{header_cells}</row>')
    for offset, row in enumerate(rows[:_MAX_XLSX_ROWS], start=2):
        cells = "".join(
            _xlsx_cell(f"{_column_name(index)}{offset}", row.get(key, ""))
            for index, (key, _label) in enumerate(COLUMNS)
        )
        sheet_rows.append(f'<row r="{offset}">{cells}</row>')
    truncated = (
        f'<row r="{len(rows[:_MAX_XLSX_ROWS]) + 2}">'
        f'<c r="A{len(rows[:_MAX_XLSX_ROWS]) + 2}" t="inlineStr"><is><t>'
        f"{escape(GENERATED_NOTE)}</t></is></c></row>"
        if len(rows) > _MAX_XLSX_ROWS
        else ""
    )
    sheet_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
        "<sheetData>" + "".join(sheet_rows) + truncated + "</sheetData></worksheet>"
    )

    safe_sheet = escape(sheet_name)[:31]
    workbook_xml = _XLSX_WORKBOOK.replace(
        'name="Intelligence"', f'name="{safe_sheet}"'
    )

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        # Fixed timestamps keep the output byte-stable for the same input.
        info = zipfile.ZipInfo("[Content_Types].xml", date_time=(1980, 1, 1, 0, 0, 0))
        archive.writestr(info, _XLSX_CONTENT_TYPES)
        for name, content in (
            ("_rels/.rels", _XLSX_RELS),
            ("xl/workbook.xml", workbook_xml),
            ("xl/_rels/workbook.xml.rels", _XLSX_WORKBOOK_RELS),
            ("xl/styles.xml", _XLSX_STYLES),
            ("xl/worksheets/sheet1.xml", sheet_xml),
        ):
            entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            archive.writestr(entry, content)
    return buffer.getvalue()


